CREATE TABLE IF NOT EXISTS detalle_transformacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_proceso_id BIGINT NOT NULL
        REFERENCES version_proceso_etl (id) ON DELETE CASCADE,
    componente_id BIGINT NOT NULL
        REFERENCES componente (id) ON DELETE CASCADE,
    total_pasos INTEGER NOT NULL DEFAULT 0 CHECK (total_pasos >= 0),
    total_hops INTEGER NOT NULL DEFAULT 0 CHECK (total_hops >= 0),
    tiene_sql BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_extraccion TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_detalle_transformacion_version
        UNIQUE (version_proceso_id, componente_id)
);

CREATE INDEX IF NOT EXISTS ix_detalle_transformacion_componente
    ON detalle_transformacion (componente_id);

CREATE TABLE IF NOT EXISTS script_sql_transformacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_transformacion_id BIGINT NOT NULL
        REFERENCES detalle_transformacion (id) ON DELETE CASCADE,
    nombre_paso VARCHAR(500) NOT NULL,
    tipo_paso VARCHAR(200),
    sql_sanitizado TEXT NOT NULL,
    hash_sql VARCHAR(64) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT uq_script_sql_transformacion_orden
        UNIQUE (detalle_transformacion_id, orden)
);

CREATE INDEX IF NOT EXISTS ix_script_sql_transformacion_detalle
    ON script_sql_transformacion (detalle_transformacion_id);

CREATE TABLE IF NOT EXISTS tabla_transformacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_transformacion_id BIGINT NOT NULL
        REFERENCES detalle_transformacion (id) ON DELETE CASCADE,
    nombre_paso VARCHAR(500),
    esquema VARCHAR(500),
    nombre VARCHAR(500) NOT NULL,
    nombre_completo VARCHAR(1000) NOT NULL,
    tipo_uso VARCHAR(20) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT ck_tabla_transformacion_tipo_uso CHECK (
        tipo_uso IN ('CONSULTA', 'DESTINO', 'LOOKUP')
    ),
    CONSTRAINT uq_tabla_transformacion_uso UNIQUE (
        detalle_transformacion_id,
        nombre_paso,
        nombre_completo,
        tipo_uso
    )
);

CREATE INDEX IF NOT EXISTS ix_tabla_transformacion_detalle
    ON tabla_transformacion (detalle_transformacion_id);

CREATE INDEX IF NOT EXISTS ix_tabla_transformacion_nombre
    ON tabla_transformacion (nombre_completo);

COMMENT ON TABLE detalle_transformacion IS
    'Resumen tecnico versionado de cada transformacion documentada.';

COMMENT ON TABLE script_sql_transformacion IS
    'Scripts SQL sanitizados detectados en los pasos de una transformacion.';

COMMENT ON TABLE tabla_transformacion IS
    'Tablas consultadas, de lookup o de destino usadas por una transformacion.';
