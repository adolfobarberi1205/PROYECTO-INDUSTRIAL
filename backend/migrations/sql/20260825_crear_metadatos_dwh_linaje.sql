CREATE TABLE IF NOT EXISTS tabla_dwh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id BIGINT NOT NULL REFERENCES proceso_etl (id) ON DELETE CASCADE,
    categoria VARCHAR(20) NOT NULL,
    nombre VARCHAR(500) NOT NULL,
    nombre_resuelto VARCHAR(500),
    esquema VARCHAR(500),
    esquema_resuelto VARCHAR(500),
    nombre_completo VARCHAR(1000) NOT NULL,
    CONSTRAINT ck_tabla_dwh_categoria CHECK (categoria IN ('DIMENSION', 'FACT')),
    CONSTRAINT uq_tabla_dwh_proceso UNIQUE (proceso_id, categoria, nombre_completo)
);

CREATE INDEX IF NOT EXISTS ix_tabla_dwh_proceso
    ON tabla_dwh (proceso_id);

CREATE TABLE IF NOT EXISTS deteccion_tabla_dwh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_dwh_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    transformacion VARCHAR(500),
    ruta_transformacion VARCHAR(1000),
    step VARCHAR(500),
    tipo_step VARCHAR(200),
    operacion VARCHAR(100),
    criterio TEXT,
    confianza VARCHAR(50),
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0)
);

CREATE TABLE IF NOT EXISTS campo_tabla_dwh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_dwh_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    nombre VARCHAR(500) NOT NULL,
    campo_flujo VARCHAR(500),
    rol VARCHAR(100),
    tipo_origen VARCHAR(100),
    detalle TEXT,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT uq_campo_tabla_dwh UNIQUE (tabla_dwh_id, nombre)
);

CREATE TABLE IF NOT EXISTS origen_campo_dwh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campo_id BIGINT NOT NULL REFERENCES campo_tabla_dwh (id) ON DELETE CASCADE,
    categoria VARCHAR(40) NOT NULL,
    nombre TEXT NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT ck_origen_campo_categoria CHECK (
        categoria IN ('CAMPO', 'TABLA', 'FUENTE', 'CLAVE_DIMENSION', 'PASO')
    )
);

CREATE TABLE IF NOT EXISTS relacion_fact_dimension (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fact_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    dimension_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    CONSTRAINT uq_relacion_fact_dimension UNIQUE (fact_id, dimension_id),
    CONSTRAINT ck_relacion_fact_dimension_distinta CHECK (fact_id <> dimension_id)
);

CREATE TABLE IF NOT EXISTS fuente_tabla_dwh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_dwh_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    tipo_fuente VARCHAR(60) NOT NULL,
    nombre VARCHAR(1000) NOT NULL,
    esquema VARCHAR(500),
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0)
);

CREATE TABLE IF NOT EXISTS etapa_construccion_tabla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_dwh_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    nombre VARCHAR(1000) NOT NULL,
    tipo VARCHAR(200),
    funcion TEXT,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0)
);

CREATE TABLE IF NOT EXISTS variable_etl (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id BIGINT NOT NULL REFERENCES proceso_etl (id) ON DELETE CASCADE,
    nombre VARCHAR(500) NOT NULL,
    alcance VARCHAR(100),
    CONSTRAINT uq_variable_etl_proceso UNIQUE (proceso_id, nombre)
);

CREATE TABLE IF NOT EXISTS uso_variable (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable_id BIGINT NOT NULL REFERENCES variable_etl (id) ON DELETE CASCADE,
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    componente_nombre VARCHAR(1000),
    tipo_uso VARCHAR(50) NOT NULL,
    evidencia TEXT,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT ck_uso_variable_tipo CHECK (
        tipo_uso IN ('PROCESO', 'COMPONENTE', 'EVIDENCIA')
    )
);

CREATE TABLE IF NOT EXISTS transicion_variable (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id BIGINT NOT NULL REFERENCES proceso_etl (id) ON DELETE CASCADE,
    variable_origen_id BIGINT REFERENCES variable_etl (id) ON DELETE SET NULL,
    variable_destino_id BIGINT REFERENCES variable_etl (id) ON DELETE SET NULL,
    variable_origen_nombre VARCHAR(500),
    variable_destino_nombre VARCHAR(500),
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    tipo_evento VARCHAR(100),
    componente_nombre VARCHAR(1000),
    detalle TEXT,
    estado VARCHAR(100),
    alcance VARCHAR(100),
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0)
);

ALTER TABLE transicion_variable
    ADD COLUMN IF NOT EXISTS variable_origen_nombre VARCHAR(500),
    ADD COLUMN IF NOT EXISTS variable_destino_nombre VARCHAR(500);

CREATE TABLE IF NOT EXISTS parametro_etl (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id BIGINT NOT NULL REFERENCES proceso_etl (id) ON DELETE CASCADE,
    nombre VARCHAR(500) NOT NULL,
    CONSTRAINT uq_parametro_etl_proceso UNIQUE (proceso_id, nombre)
);

CREATE TABLE IF NOT EXISTS uso_parametro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parametro_id BIGINT NOT NULL REFERENCES parametro_etl (id) ON DELETE CASCADE,
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    componente_nombre VARCHAR(1000),
    tipo_uso VARCHAR(50) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    CONSTRAINT ck_uso_parametro_tipo CHECK (
        tipo_uso IN ('DECLARADO', 'REFERENCIADO', 'LLAMADA')
    )
);

CREATE TABLE IF NOT EXISTS asignacion_variable_parametro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id BIGINT NOT NULL REFERENCES proceso_etl (id) ON DELETE CASCADE,
    variable_id BIGINT NOT NULL REFERENCES variable_etl (id) ON DELETE CASCADE,
    parametro_id BIGINT NOT NULL REFERENCES parametro_etl (id) ON DELETE CASCADE,
    componente_id BIGINT REFERENCES componente (id) ON DELETE SET NULL,
    componente_nombre VARCHAR(1000) NOT NULL DEFAULT '',
    CONSTRAINT uq_asignacion_variable_parametro UNIQUE (
        proceso_id, variable_id, parametro_id, componente_nombre
    )
);

ALTER TABLE asignacion_variable_parametro
    ADD COLUMN IF NOT EXISTS componente_id BIGINT
        REFERENCES componente (id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS componente_nombre VARCHAR(1000)
        NOT NULL DEFAULT '';

ALTER TABLE asignacion_variable_parametro
    DROP CONSTRAINT IF EXISTS uq_asignacion_variable_parametro;

ALTER TABLE asignacion_variable_parametro
    ADD CONSTRAINT uq_asignacion_variable_parametro UNIQUE (
        proceso_id, variable_id, parametro_id, componente_nombre
    );

CREATE TABLE IF NOT EXISTS tabla_dwh_variable (
    tabla_dwh_id BIGINT NOT NULL REFERENCES tabla_dwh (id) ON DELETE CASCADE,
    variable_id BIGINT NOT NULL REFERENCES variable_etl (id) ON DELETE CASCADE,
    tipo_uso VARCHAR(50) NOT NULL DEFAULT 'CONSTRUCCION',
    PRIMARY KEY (tabla_dwh_id, variable_id, tipo_uso)
);

CREATE INDEX IF NOT EXISTS ix_campo_tabla_dwh_tabla
    ON campo_tabla_dwh (tabla_dwh_id);
CREATE INDEX IF NOT EXISTS ix_variable_etl_proceso
    ON variable_etl (proceso_id);
CREATE INDEX IF NOT EXISTS ix_parametro_etl_proceso
    ON parametro_etl (proceso_id);
CREATE INDEX IF NOT EXISTS ix_transicion_variable_proceso
    ON transicion_variable (proceso_id);

COMMENT ON TABLE tabla_dwh IS
    'Tablas DIM y FACT creadas por un proceso ETL documentado.';
COMMENT ON TABLE campo_tabla_dwh IS
    'Campos finales de DIM y FACT con su clasificacion de origen.';
COMMENT ON TABLE variable_etl IS
    'Variables documentadas sin almacenar sus valores sensibles.';
COMMENT ON TABLE parametro_etl IS
    'Parametros documentados sin valores por defecto sensibles.';
