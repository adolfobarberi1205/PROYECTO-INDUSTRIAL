CREATE TABLE IF NOT EXISTS diagrama (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    componente_id BIGINT NOT NULL,
    ancho_recomendado INTEGER NOT NULL,
    alto_recomendado INTEGER NOT NULL,
    CONSTRAINT fk_diagrama_componente
        FOREIGN KEY (componente_id)
        REFERENCES componente (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_diagrama_componente
        UNIQUE (componente_id),
    CONSTRAINT ck_diagrama_ancho_positivo
        CHECK (ancho_recomendado > 0),
    CONSTRAINT ck_diagrama_alto_positivo
        CHECK (alto_recomendado > 0)
);

CREATE TABLE IF NOT EXISTS elemento_diagrama (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagrama_id BIGINT NOT NULL,
    clave_origen VARCHAR(1500) NOT NULL,
    nombre VARCHAR(500) NOT NULL,
    tipo VARCHAR(200) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    x_original DOUBLE PRECISION NOT NULL,
    y_original DOUBLE PRECISION NOT NULL,
    x_visual DOUBLE PRECISION NOT NULL,
    y_visual DOUBLE PRECISION NOT NULL,
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    navegable BOOLEAN NOT NULL DEFAULT FALSE,
    componente_destino_id BIGINT,
    estado_destino VARCHAR(80),
    orden INTEGER NOT NULL,
    CONSTRAINT fk_elemento_diagrama
        FOREIGN KEY (diagrama_id)
        REFERENCES diagrama (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_elemento_componente_destino
        FOREIGN KEY (componente_destino_id)
        REFERENCES componente (id)
        ON DELETE SET NULL,
    CONSTRAINT uq_elemento_diagrama_clave
        UNIQUE (diagrama_id, clave_origen),
    CONSTRAINT ck_elemento_diagrama_categoria
        CHECK (categoria IN ('ENTRY', 'STEP')),
    CONSTRAINT ck_elemento_diagrama_orden
        CHECK (orden >= 0)
);

CREATE INDEX IF NOT EXISTS ix_elemento_diagrama_diagrama
    ON elemento_diagrama (diagrama_id);

CREATE INDEX IF NOT EXISTS ix_elemento_diagrama_destino
    ON elemento_diagrama (componente_destino_id);

CREATE TABLE IF NOT EXISTS hop_diagrama (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagrama_id BIGINT NOT NULL,
    clave_origen VARCHAR(64) NOT NULL,
    nombre_origen VARCHAR(500) NOT NULL,
    nombre_destino VARCHAR(500) NOT NULL,
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    evaluacion VARCHAR(100),
    incondicional BOOLEAN NOT NULL DEFAULT FALSE,
    orden INTEGER NOT NULL,
    CONSTRAINT fk_hop_diagrama
        FOREIGN KEY (diagrama_id)
        REFERENCES diagrama (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_hop_diagrama_clave
        UNIQUE (diagrama_id, clave_origen),
    CONSTRAINT ck_hop_diagrama_orden
        CHECK (orden >= 0)
);

CREATE INDEX IF NOT EXISTS ix_hop_diagrama_diagrama
    ON hop_diagrama (diagrama_id);

COMMENT ON TABLE diagrama IS
    'Lienzo navegable de un Job o Transformacion documentado.';

COMMENT ON TABLE elemento_diagrama IS
    'Entries o Steps con posicion original y posicion editable.';

COMMENT ON TABLE hop_diagrama IS
    'Conexiones visuales entre elementos de un diagrama.';
